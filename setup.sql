-- Create tables
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  file_url text not null,
  file_path text not null,
  published boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
alter table public.sections enable row level security;
alter table public.materials enable row level security;

-- Admin helper. Security-definer avoids recursive RLS checks on admin_users.
create or replace function public.is_site_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to authenticated;

-- Public can read published learning content; only admins can change it.
create policy "Public read published sections" on public.sections for select using (published = true or public.is_site_admin());
create policy "Admins insert sections" on public.sections for insert to authenticated with check (public.is_site_admin());
create policy "Admins update sections" on public.sections for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
create policy "Admins delete sections" on public.sections for delete to authenticated using (public.is_site_admin());

create policy "Public read published materials" on public.materials for select using (published = true or public.is_site_admin());
create policy "Admins insert materials" on public.materials for insert to authenticated with check (public.is_site_admin());
create policy "Admins update materials" on public.materials for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
create policy "Admins delete materials" on public.materials for delete to authenticated using (public.is_site_admin());

create policy "Admins read admin list" on public.admin_users for select to authenticated using (public.is_site_admin());

-- Storage buckets: learning documents are publicly downloadable, but only admins upload/delete.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('materials', 'materials', true, 52428800,
  array['application/pdf','application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document','application/vnd.ms-powerpoint','application/vnd.openxmlformats-officedocument.presentationml.presentation','image/jpeg','image/png'])
on conflict (id) do nothing;
create policy "Public read materials files" on storage.objects for select using (bucket_id = 'materials');
create policy "Admins upload materials files" on storage.objects for insert to authenticated with check (bucket_id = 'materials' and public.is_site_admin());
create policy "Admins update materials files" on storage.objects for update to authenticated using (bucket_id = 'materials' and public.is_site_admin()) with check (bucket_id = 'materials' and public.is_site_admin());
create policy "Admins delete materials files" on storage.objects for delete to authenticated using (bucket_id = 'materials' and public.is_site_admin());

